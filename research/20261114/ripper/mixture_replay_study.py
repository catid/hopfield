def prepare():
    import numpy as np
    from mixture_replay_policy import thresholds
    p=verify(full=True); assert not OUT.exists(); OUT.mkdir(parents=True)
    parent=json.loads((PARENT/'audit.json').read_text())
    assert parent['status']=='validated' and parent['primary']['pooled_extra_edges']==2588
    assert parent['protocol_sha256']==sha(HERE/'protocol-adaptive-null.json')
    assert parent['continuation_protocol_sha256']==sha(HERE/'protocol-adaptive-null-continuation.json')
    source=[]
    for seed in p['seeds']:
        d=PARENT/f's{seed}'; receipt=json.loads((d/'receipt.json').read_text())
        audit=json.loads((d/'audit.json').read_text()); events=json.loads((d/'events.json').read_text())
        assert audit['status']=='validated' and audit['auditor_sha256']==sha(HERE/'audit_adaptive_null_eager.py')
        assert audit['receipt_sha256']==sha(d/'receipt.json')
        assert audit['protocol_sha256']==receipt['protocol_sha256']==parent['protocol_sha256']
        assert receipt['queries']==27750 and receipt['mask_finalized_before_current_noise']==1110
        assert len(events)==1110
        for row,event in enumerate(events):
            assert event['row']==row and event['mask_finalized_before_current_corruption'] is True
        for name in ['observations.npz','fit.npz','events.json']:
            assert receipt['artifact_sha256'][name]==sha(d/name)
        source.append(dict(seed=seed,parent_receipt_sha256=sha(d/'receipt.json'),parent_audit_sha256=sha(d/'audit.json'),
                           parent_observations_sha256=sha(d/'observations.npz'),historical_queries=27750,predictable_masks=1110))
    save(OUT/'source-audit.json',dict(status='validated',protocol_sha256=sha(PROTOCOL),banks=source,
                                    historical_queries=888000,new_queries=0,predictable_masks=35520))
    np.savez_compressed(OUT/'thresholds.npz',thresholds=thresholds())
    from audit_mixture_replay import audit_thresholds
    audit_thresholds()


def bank(seed):
    import numpy as np
    from mixture_replay_policy import counts_step, log_likelihoods, mixture_log
    started=time.monotonic();p=verify(seed); assert seed in p['seeds']
    obs=load_npz(PARENT/f's{seed}'/'observations.npz'); threshold=load_npz(OUT/'thresholds.npz')['thresholds']
    joint=np.zeros((81,81),np.int32);equal=np.zeros_like(joint);pair=np.triu_indices(81,1)
    first=np.full((2,3240),-1,np.int32);digests=[]
    for row in range(1110):
        counts_step(joint,equal,obs['given'][row],obs['values'][row]);m,c=joint[pair],equal[pair]
        digests.append(hashlib.sha256(m.tobytes()+c.tobytes()).hexdigest())
        first[(first<0)&(c[None,:]>=threshold[:,m])]=row+1
    np.savez_compressed(OUT/f's{seed}.npz',joint_count=m,equal_count=c,first_crossing=first,support=first<0,
                        final_only_support=c[None,:]<threshold[:,m],count_sha256=np.array(digests),
                        final_component_log_lr=log_likelihoods(m,c),final_mixture_log_lr=mixture_log(m,c))
    from audit_mixture_replay import audit_bank
    result=audit_bank(seed);save(OUT/f's{seed}-receipt.json',dict(status='complete',seed=seed,wall_s=time.monotonic()-started,
             protocol_sha256=sha(PROTOCOL),producer_sha256=sha(__file__),model_sha256=sha(OUT/f's{seed}.npz'),
             audit_sha256=sha(OUT/f's{seed}-audit.json')))
    print(json.dumps(dict(seed=seed,status=result['status'])),flush=True)


def summary():
    import numpy as np
    p=verify();rows=[];audits=[];models=[];hashes={}
    for seed in p['seeds']:
        a=json.loads((OUT/f's{seed}-audit.json').read_text());r=json.loads((OUT/f's{seed}-receipt.json').read_text())
        assert a['status']=='validated' and r['status']=='complete'
        assert a['protocol_sha256']==r['protocol_sha256']==sha(PROTOCOL)
        assert a['auditor_sha256']==sha(HERE/'audit_mixture_replay.py')
        assert a['model_sha256']==r['model_sha256']==sha(OUT/f's{seed}.npz')
        assert r['audit_sha256']==sha(OUT/f's{seed}-audit.json')
        rows+=a['rows'];audits.append(a);models.append(load_npz(OUT/f's{seed}.npz')['support'])
        for suffix in ['.npz','-audit.json','-receipt.json']:
            path=OUT/f's{seed}{suffix}';hashes[str(path.relative_to(ROOT))]=sha(path)
    grouped=[]
    for arm in ARMS:
        selected=[r for r in rows if r['arm']==arm];assert len(selected)==32
        grouped.append(dict(arm=arm,**{k:sum(r[k] for r in selected) for k in
                         ['missing_true_edges','extra_edges','all_true_retained','exact_graph','final_only_reinstated_pairs']}))
    assert grouped[0]['missing_true_edges']==0 and grouped[0]['extra_edges']==2588
    g=grouped[1];retention=g['missing_true_edges']==0;extras=g['extra_edges']<=1941
    primary=dict(decision='supported_finite_bank_conjunction' if retention and extras else 'falsified_finite_bank_conjunction',
                 missing_true_edges=g['missing_true_edges'],pooled_extra_edges=g['extra_edges'],extra_ceiling=1941,
                 retention_target_met=retention,extra_target_met=extras,extra_reduction_pct=100*(1-g['extra_edges']/2588))
    np.savez_compressed(PUBLIC/'mixture_replay_supports.npz',banks=np.arange(32),arms=np.array(ARMS),supports=np.stack(models))
    result=dict(status='validated',protocol_sha256=sha(PROTOCOL),summarizer_sha256=sha(__file__),scope=p['scope'],
                primary=primary,grouped=grouped,rows=rows,bank_audits=audits,
                threshold_audit=json.loads((OUT/'threshold-audit.json').read_text()),
                source_audit=json.loads((OUT/'source-audit.json').read_text()),
                artifact_sha256=hashes,support_export_sha256=sha(PUBLIC/'mixture_replay_supports.npz'),
                cumulative_pair_states_checked=115084800,original_first_crossing_paths_matched=103680,
                mixture_first_crossing_paths_checked=103680,all_banks_retained=True,
                **p['query_accounting'],gpu_seconds=0)
    save(OUT/'audit.json',result);save(PUBLIC/'mixture_replay.json',result)
    with (PUBLIC/'mixture_replay_per_bank.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
    print(json.dumps(dict(primary=primary,grouped=grouped)),flush=True)


