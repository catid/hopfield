        primary='Conjunction: zero missing true edge-bank pairs AND mixture extras <= 1941, a >= 25% reduction from the archived 2588. Supported iff both pass; otherwise falsified. All 32 banks retained. No fresh-source or population-confidence claim.',
        controls='BP AdamW is outside this source-only study, not run. Original q1=1/9 is independently replayed and must exactly match every H1as first-crossing path, final count and support. No alternative grid search.',
