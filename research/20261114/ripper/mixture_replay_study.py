def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + '\n')
    temporary.replace(path)


def load_npz(path):
    import numpy as np
    with np.load(path, allow_pickle=False) as z:
        return {name: z[name].copy() for name in z.files}


def verify(seed=None, full=False):
    p = json.loads(PROTOCOL.read_text())
    for path, digest in (p['code_sha256'] | p['input_sha256']).items():
        assert sha(ROOT / path) == digest, path
    banks = range(32) if full else ([] if seed is None else [seed])
    for bank in banks:
        for name, digest in p['bank_sha256'][str(bank)].items():
            assert sha(PARENT / f's{bank}' / name) == digest, (bank, name)
    return p


